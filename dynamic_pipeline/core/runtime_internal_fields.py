def strip_runtime_internal_fields(value: Any) -> Any:
    if isinstance(value, dict):
        output: dict[str, Any] = {}
        for key, item in value.items():
            key_text = str(key)
            if key_text in RUNTIME_INTERNAL_FIELDS:
                continue
            output[key_text] = strip_runtime_internal_fields(item)
        return output
    if isinstance(value, list):
        return [strip_runtime_internal_fields(item) for item in value]
    if isinstance(value, tuple):
        return [strip_runtime_internal_fields(item) for item in value]
    return value
